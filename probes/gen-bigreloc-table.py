"""Emit bigreloc_table.S: N absolute pointers, N R_AARCH64_ABS64 relocations."""
import sys
n = int(sys.argv[1]) if len(sys.argv) > 1 else 2_000_000
print("/* generated by gen-bigreloc-table.py */")
print(".section .data\n.globl bigreloc_table\n.p2align 3\nbigreloc_table:")
print(".rept %d\n.quad bigreloc_table\n.endr" % n)
print(".globl bigreloc_count\nbigreloc_count:\n.quad %d" % n)
